// Screen the coming Daily Rites for winnability, and write the table the game
// settles each day's seed from (src/systems/DailyDraws.ts).
//
// Run: npm run daily:screen            (DAYS=400 from today; FROM=YYYY-MM-DD)
//      VERIFY=1 npm run daily:screen   (re-play the table as it stands)
//
// A day's seed fixes every roll, shelf and boss it deals, so some seeds are
// simply lost: a wall at trial four that no purchase gets past is a wall for
// every player that day. Each day here draws its seeds in turn (Daily.seedDraw)
// and plays each one out with a panel of balance bots, on the day's own named
// streams (SimConfig.addressedStreams) and under its boons, banes and novice,
// and keeps the first draw the bots win three times. A bot winning is proof the day can be
// won; the bots are weaker than a good player, so a day they all lose is not
// proof it cannot, but it is the day the screen turns away.
//
// The table is only as true as the rules it was screened under. A change to
// the game's balance can make a screened day harder (or move what its seed
// deals), so re-screen after one: VERIFY=1 lists the days that no longer hold.

import { writeFileSync } from "node:fs";
import {
  applyDailyRite,
  dailyDay,
  dailyShopUnlocks,
  MAX_SEED_DRAWS,
  opensCleanly,
  riteForDraw,
  screenedDraw,
  type DailyRite,
} from "../systems/Daily";
import { SCREENED_FROM } from "../systems/DailyDraws";
import { simulateRun, type StrategyName } from "./bot";
import { DEFAULT_CONFIG } from "./config";
import { installStorage } from "./localStorageShim";

/** The panel, strongest first so a winnable draw is usually settled on the
 *  first run. Only the quick shoppers: the expert appraises every shelf and
 *  would take hours over a year of days. */
const PANEL: StrategyName[] = [
  "economy",
  "player",
  "pyre",
  "swarm",
  "multiplier",
  "tempo",
  "weighing",
  "resonance",
  "thrifty",
];
/** Each bot plays a draw this many times, choosing differently each time. */
const ATTEMPTS = 3;

const unlocks = dailyShopUnlocks();
installStorage([...unlocks]);

/** How many of the panel's runs must win a draw for the day to keep it. More
 *  than one, so a day is never kept on a single lucky line through it, and
 *  enough that a day kept is one a capable player can find the way through. */
const WINS_NEEDED = 3;

/** The runs that won `rite`, once WINS_NEEDED have, or null if too few did. */
function won(rite: DailyRite): string | null {
  if (!opensCleanly(rite)) return null;
  const winners: string[] = [];
  for (let attempt = 1; attempt <= ATTEMPTS; attempt++) {
    for (const strategy of PANEL) {
      const record = simulateRun(strategy, attempt, {
        ...DEFAULT_CONFIG,
        unlockedAtStart: unlocks,
        character: rite.character,
        addressedStreams: true,
        contentSeed: rite.seed,
        prepareRun: (state) => applyDailyRite(state, rite),
      });
      if (record.won) winners.push(`${strategy}#${attempt}`);
      if (winners.length >= WINS_NEEDED) return winners.join(" ");
    }
  }
  return null;
}

const DAY_MS = 86_400_000;
const dayAfter = (day: string, n: number) =>
  dailyDay(Date.parse(`${day}T12:00:00Z`) + n * DAY_MS);

if (process.env.VERIFY) {
  let broken = 0;
  for (let i = 0; ; i++) {
    const day = dayAfter(SCREENED_FROM, i);
    const draw = screenedDraw(day);
    if (draw === null) break;
    const by = won(riteForDraw(day, draw));
    if (!by) broken += 1;
    console.log(
      `${day}  draw ${String(draw).padStart(2)}  ${by ?? "NO LONGER WON"}`,
    );
  }
  console.log(
    broken
      ? `\n${broken} day(s) need re-screening.`
      : "\nEvery screened day still holds.",
  );
  process.exit(broken ? 1 : 0);
}

const from = process.env.FROM ?? dailyDay();
const days = Math.max(1, Number(process.env.DAYS ?? 400) | 0);
const draws: number[] = [];
for (let i = 0; i < days; i++) {
  const day = dayAfter(from, i);
  let chosen = -1;
  let by: string | null = null;
  for (let draw = 0; draw < MAX_SEED_DRAWS && chosen < 0; draw++) {
    by = won(riteForDraw(day, draw));
    if (by) chosen = draw;
  }
  if (chosen < 0) {
    // Never seen, but a table must not hold a hole: leave the day to the
    // runtime's opening-trial bar rather than to an unscreened guess.
    console.log(`${day}  no draw won in ${MAX_SEED_DRAWS}; left unscreened`);
  } else {
    const rite = riteForDraw(day, chosen);
    console.log(
      `${day}  draw ${String(chosen).padStart(2)}  ${by!.padEnd(26)} ${rite.character.padEnd(8)} ${[...rite.boons, ...rite.banes].join(", ")}`,
    );
  }
  draws.push(chosen);
}

writeFileSync(
  new URL("../systems/DailyDraws.ts", import.meta.url),
  `// GENERATED by \`npm run daily:screen\` (src/sim/dailyScreen.ts). Do not edit.
//
// For each day from SCREENED_FROM on, the first of that day's seed draws
// (Daily.seedDraw) that a balance bot carried to victory on the day's own dice
// and shelves. -1 is a day no draw was won on, left to the runtime's bar. See
// Daily.dailyRite.

export const SCREENED_FROM = ${JSON.stringify(from)};

// prettier-ignore
export const SCREENED_DRAWS: readonly number[] = [
${chunk(draws, 30)
  .map((row) => `  ${row.join(", ")},`)
  .join("\n")}
];
`,
);
console.log(
  `\nWrote ${draws.length} days from ${from} to src/systems/DailyDraws.ts.`,
);

function chunk<T>(items: T[], size: number): T[][] {
  const rows: T[][] = [];
  for (let i = 0; i < items.length; i += size)
    rows.push(items.slice(i, i + size));
  return rows;
}
